#!/usr/bin/env python3
"""Build human-readable citation ledger for GitHub even when Pages is disabled."""
import json
from collections import defaultdict
from pathlib import Path

ROOT=Path(__file__).resolve().parent
PAPERS=json.loads((ROOT/"docs/papers.json").read_text(encoding="utf-8"))
VERIFIED=json.loads((ROOT/"docs/verified.json").read_text(encoding="utf-8"))
DISCOVERED=json.loads((ROOT/"docs/discovered.json").read_text(encoding="utf-8"))
def key(c):
    return c.get("doi") or c.get("arxiv") or (c.get("platform","")+":"+str(c.get("id",""))) or c.get("title","").lower()
def link(p):
    if p.get("doi"):return "https://doi.org/"+p["doi"]
    if p.get("arxiv"):return "https://arxiv.org/abs/"+p["arxiv"]
    if p.get("hexagon"):return "https://hexagonmath.org/"+p["hexagon"]
    return ""
def citing_url(c):
    if c.get("url"):return c["url"]
    if c.get("platform")=="hexagon":return "https://hexagonmath.org/"+str(c.get("id",""))
    if c.get("platform")=="arxiv":return "https://arxiv.org/abs/"+str(c.get("id",""))
    return ""
def name(s):
    return str(s).replace("|","/").replace("\n"," ").strip()
def surname(s):
    return s.strip().split()[-1].lower() if s.strip() else ""
def independent(p,c):
    authors=[a.strip() for a in c.get("authors","").split(";") if a.strip()]
    if not authors or not p.get("authors"):return False
    known={surname(s) for s in p["authors"]}
    return all(surname(a) not in known for a in authors)
groups=defaultdict(dict)
for c in VERIFIED:
    if c.get("verified"):groups[c["target"]][key(c)]=c
candidate=defaultdict(dict)
for c in DISCOVERED.get("citations",[]):
    if key(c) not in groups[c["target"]]:
        candidate[c["target"]][key(c)]=c
count=sum(len(v) for v in groups.values())
unique=len({(c.get("doi") or c.get("arxiv") or c.get("title","").lower()) for v in groups.values() for c in v.values()})
ind=sum(independent(p,c) for p in PAPERS for c in groups[p["id"]].values())
candidate_count=sum(len(v) for v in candidate.values())
lines=[
"# Citation evidence — Nhat Minh Doan",
"",
"> **Verified lower bound, not an exact worldwide total.** This report distinguishes inspected bibliography references from indexed candidates. Duplicate citing versions and author name variations remain subject to review.",
"",
f"**Verified citation relationships:** {count} | **Independent verified:** {ind} | **Distinct verified citing works:** {unique} | **Indexed-only candidates:** {candidate_count} | **Papers tracked:** {len(PAPERS)}",
"",
"| Canonical paper | Verified citations | Indexed candidates |",
"|---|---:|---:|"
]
for p in sorted(PAPERS,key=lambda p:len(groups[p["id"]]),reverse=True):
    label=name(p["title"])
    url=link(p)
    cell=f"[{label}]({url})" if url else label
    lines.append(f"| {cell} | {len(groups[p['id']])} | {len(candidate[p['id']])} |")
lines+=["", "## Verified bibliography references", ""]
for p in sorted(PAPERS,key=lambda p:len(groups[p["id"]]),reverse=True):
    if not groups[p["id"]]:continue
    lines += ["### "+name(p["title"]),"",]
    for c in sorted(groups[p["id"]].values(),key=lambda c:c.get("title","")):
        title=name(c.get("title",""))
        url=citing_url(c)
        a=", ".join([name(v) for v in c.get("authors","").split(";") if v.strip()])
        label=(f"[{title}]({url})" if url else title)
        kind="independent" if independent(p,c) else "coauthor overlap/unknown"
        lines.append(f"- {label} — {a or 'author unavailable'}; {kind}. Source: {name(c.get('source',''))}.")
    lines.append("")
lines+=["## Collection status", "",
        f"Last indexed discovery: {DISCOVERED.get('generated_utc') or 'not yet completed'}.",
        "",
        "This public report is generated by GitHub Actions from [canonical paper data](docs/papers.json), [verified references](docs/verified.json), and [unverified database matches](docs/discovered.json).",
        "Google Scholar and ResearchGate numbers are not automatically treated as evidence.",
        ""]
(ROOT/"CITATIONS.md").write_text("\n".join(lines),encoding="utf-8")
print("Wrote CITATIONS.md", count, candidate_count)
